# Removendo pelo índice

fila_atendimento = ["Ana", "Carlos", "Mariana", "Pedro", "Lucas"]
print(fila_atendimento)

usuario_removido_1 = fila_atendimento.pop(-1)
print("Usuário removido:", usuario_removido_1)

print(fila_atendimento)

usuario_removido_2 = fila_atendimento.pop(-4)
print("Usuário removido:", usuario_removido_2)

print(fila_atendimento)
