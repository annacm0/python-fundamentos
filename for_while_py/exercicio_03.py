# Quantas vezes a mensagem será exibida?

# range(5) cria uma sequência de números de 0 a 4 (ou seja, 0, 1, 2, 3, 4).
# O for vai "passar" por cada um desses números. A cada "passagem", o valor atual é atribuído à variável i.
# i = índice, item, iterador
for i in range(5): 
    print("Bem-vindo ao Buscante!")

# Quando você precisa repetir uma ação um número específico de vezes (como 5 vezes, 10 vezes, etc.), o range() é a ferramenta perfeita para usar com o laço for.

# Então, a dica é: quando o problema te dá um número fixo de repetições, como "exibir 5 vezes", "fazer 10 iterações", range() é a primeira coisa que deve vir à mente para usar com o for!

# for (o laço): Ele é o "maestro" que comanda a repetição. A função do for é dizer: "Eu vou executar um bloco de código repetidamente para cada item em uma sequência."

# range() (a sequência): Ele é o "gerador de números" que o for usa. A função do range() é criar uma sequência de números (por exemplo, de 0 a 4, se for range(5)). Ele não faz a repetição sozinho, apenas fornece os "passos" para o for seguir.